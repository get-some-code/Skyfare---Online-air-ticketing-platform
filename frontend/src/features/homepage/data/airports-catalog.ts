/**
 * Helper to match query against city, country, airport name, or 3-letter IATA code.
 */
export function searchAirports(query: string, regionFilter?: string): AirportItem[] {
  const clean = query.trim().toLowerCase();

  let list = ALL_AIRPORTS;
  if (regionFilter && regionFilter !== "All") {
    if (regionFilter === "Popular") {
      list = list.filter((a) => a.popular);
    } else {
      list = list.filter((a) => a.region === regionFilter);
    }
  }

  if (!clean) {
    return list;
  }

  return list.filter((a) => {
    return (
      a.code.toLowerCase().includes(clean) ||
      a.city.toLowerCase().includes(clean) ||
      a.country.toLowerCase().includes(clean) ||
      a.airport.toLowerCase().includes(clean) ||
      `${a.code} - ${a.city}`.toLowerCase().includes(clean)
    );
  });
}

/**
 * Returns a fast lookup map of code -> AirportItem
 */
export const AIRPORT_LOOKUP: Record<string, AirportItem> = ALL_AIRPORTS.reduce(
  (acc, curr) => {
    acc[curr.code.toUpperCase()] = curr;
    return acc;
  },
  {} as Record<string, AirportItem>,
);

export function getAirportByCode(code: string): AirportItem | undefined {
  const clean = (code || "").trim().toUpperCase();
  const match = clean.match(/^([A-Z]{3})\b/);
  const targetCode = match ? match[1] : clean.slice(0, 3);
  return AIRPORT_LOOKUP[targetCode];
}
